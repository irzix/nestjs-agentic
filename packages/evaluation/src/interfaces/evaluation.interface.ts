import type { AgentResult, ToolCallRecord } from '@nestjs-agentic/core';

/**
 * Standardized dataset item for benchmarking agent execution performance.
 */
export interface EvalDatasetItem {
  /** Unique dataset item identifier. */
  id: string;

  /** Input query or prompt string sent to the agent. */
  query: string;

  /** Expected ground truth output string or key facts. */
  expectedOutput?: string;

  /** Expected tool execution sequence (e.g. `['checkBalance', 'transferFunds']`). */
  expectedToolSequence?: string[];

  /** Expected tool argument assertions (e.g. `{ transferFunds: { amount: 500 } }`). */
  expectedToolArgs?: Record<string, Record<string, unknown>>;

  /** List of forbidden tool names or policy restrictions. */
  forbiddenTools?: string[];

  /** Maximum expected tool execution steps limit. Default: `5` */
  maxAllowedSteps?: number;

  /** Maximum expected token consumption limit. Default: `4000` */
  maxAllowedTokens?: number;

  /** Maximum expected latency in milliseconds. Default: `10000` */
  maxAllowedLatencyMs?: number;

  /** Context overrides or user roles for benchmark execution. */
  context?: {
    userId?: string;
    tenantId?: string;
    roles?: string[];
    permissions?: string[];
    data?: Record<string, unknown>;
  };
}

/**
 * Evaluation score result for a single metric on a dataset item.
 */
export interface MetricResult {
  /** Name of the metric evaluator. */
  metricName: string;

  /** Whether the metric evaluation met the pass threshold. */
  passed: boolean;

  /** Numerical mathematical score (0.0 to 1.0). */
  score: number;

  /** Detailed human-readable explanation or failure reason. */
  reason?: string;

  /** Key-value metadata breakdown of the evaluation math. */
  details?: Record<string, unknown>;
}

/**
 * Interface defining a pluggable agent evaluation metric.
 */
export interface EvalMetric {
  /** Unique name of the metric. */
  name: string;

  /**
   * Evaluates an agent execution result against a benchmark dataset item.
   * @param item Benchmark dataset item.
   * @param result Output result generated by the agent runner.
   */
  evaluate(item: EvalDatasetItem, result: AgentResult): Promise<MetricResult> | MetricResult;
}

/**
 * Statistical summary of multi-trial evaluation runs for a single dataset item.
 */
export interface MultiTrialResult {
  /** Array of scores obtained across trials. */
  scores: number[];

  /** Mean mathematical score (mu) across trials. */
  meanScore: number;

  /** Standard deviation (sigma) of scores across trials. */
  standardDeviation: number;

  /** Percentage of trials that passed (0.0 to 1.0). */
  passRate: number;
}

/**
 * Consolidated evaluation result for a single dataset item across all metrics.
 */
export interface EvalItemResult {
  /** Benchmark dataset item. */
  item: EvalDatasetItem;

  /** Agent execution result. */
  agentResult: AgentResult;

  /** Individual metric evaluation results. */
  metrics: MetricResult[];

  /** Whether all metric evaluations passed. */
  overallPassed: boolean;

  /** Consolidated average score across metrics. */
  score: number;

  /** Optional multi-trial statistical variance summary. */
  multiTrialSummary?: MultiTrialResult;
}

/**
 * Overall benchmark summary output generated after running a dataset suite.
 */
export interface BenchmarkSummary {
  /** Total number of items evaluated. */
  totalItems: number;

  /** Number of items that passed all metrics. */
  passedItems: number;

  /** Number of items that failed one or more metrics. */
  failedItems: number;

  /** Overall pass rate (0.0 to 1.0). */
  passRate: number;

  /** Overall average score across all items (0.0 to 1.0). */
  averageScore: number;

  /** Statistical overall variance across all dataset items. */
  overallVariance: number;

  /** Detailed evaluation results per dataset item. */
  itemResults: EvalItemResult[];
}
