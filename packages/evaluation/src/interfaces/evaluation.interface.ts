import type { AgentResult, ToolCallRecord } from '@nestjs-agentic/core';

/**
 * Standardized dataset item for benchmarking agent execution performance.
 */
export interface EvalDatasetItem {
  /** Unique dataset item identifier. */
  id: string;

  /** Input query or prompt string sent to the agent. */
  query: string;

  /** Expected ground truth output string or key facts. */
  expectedOutput?: string;

  /** Optimal or minimal expected tool execution sequence (e.g. `['checkBalance', 'transferFunds']`). */
  expectedToolSequence?: string[];

  /** Expected tool argument assertions (e.g. `{ transferFunds: { amount: 500 } }`). */
  expectedToolArgs?: Record<string, Record<string, unknown>>;

  /** List of forbidden tool names or policy restrictions. */
  forbiddenTools?: string[];

  /** Optimal or minimal number of steps expected to complete the task efficiently. */
  optimalSteps?: number;

  /** Maximum expected tool execution steps limit. Default: `5` */
  maxAllowedSteps?: number;

  /** Maximum expected token consumption limit. Default: `4000` */
  maxAllowedTokens?: number;

  /** Maximum expected latency in milliseconds. Default: `10000` */
  maxAllowedLatencyMs?: number;

  /** Context overrides or user roles for benchmark execution. */
  context?: {
    userId?: string;
    tenantId?: string;
    roles?: string[];
    permissions?: string[];
    data?: Record<string, unknown>;
  };
}

/**
 * Evaluation score result for a single metric on a dataset item.
 */
export interface MetricResult {
  /** Name of the metric evaluator. */
  metricName: string;

  /** Whether the metric evaluation met the pass threshold. */
  passed: boolean;

  /** Numerical mathematical score (0.0 to 1.0). */
  score: number;

  /** Detailed human-readable explanation or failure reason. */
  reason?: string;

  /** Key-value metadata breakdown of the evaluation math. */
  details?: Record<string, unknown>;
}

/**
 * Interface defining a pluggable agent evaluation metric.
 */
export interface EvalMetric {
  /** Unique name of the metric. */
  name: string;

  /**
   * Evaluates an agent execution result against a benchmark dataset item.
   * @param item Benchmark dataset item.
   * @param result Output result generated by the agent runner.
   */
  evaluate(item: EvalDatasetItem, result: AgentResult): Promise<MetricResult> | MetricResult;
}

/**
 * Candidate agent response payload evaluated in pairwise comparison.
 */
export interface PairwiseJudgeCandidate {
  /** Unique candidate identifier (e.g. model name, agent version) */
  id: string;
  /** Text response output generated by the candidate */
  output: string;
  /** Optional tool execution trajectory sequence */
  trajectory?: ToolCallRecord[];
  /** Arbitrary metadata attached to the candidate */
  metadata?: Record<string, unknown>;
}

/**
 * Input parameters passed into a pairwise LLM judge evaluation.
 */
export interface PairwiseJudgeInput {
  /** The initial prompt or task instruction */
  query: string;
  /** Candidate A */
  candidateA: PairwiseJudgeCandidate;
  /** Candidate B */
  candidateB: PairwiseJudgeCandidate;
  /** Optional evaluation criteria or rubric guidelines */
  criteria?: string;
  /** Optional ground truth or expected answer reference */
  groundTruth?: string;
}

/**
 * Result of a single directional judge pass (forward or reverse).
 */
export interface PairwisePassResult {
  /** Winner of the directional pass ('first' | 'second' | 'tie') */
  winner: 'first' | 'second' | 'tie';
  /** Score awarded to the first presented candidate [0, 1] */
  scoreFirst: number;
  /** Score awarded to the second presented candidate [0, 1] */
  scoreSecond: number;
  /** Analytical critique and reasoning from the judge */
  reasoning: string;
}

/**
 * Consolidated position-debiased pairwise judge evaluation result.
 *
 * @see Zheng et al., "Judging LLM-as-a-Judge with MT-Bench" (UC Berkeley LMSYS, NeurIPS 2023)
 */
export interface PairwiseJudgeResult {
  /** Definitive winner after position debiasing ('candidate_a' | 'candidate_b' | 'tie') */
  winner: 'candidate_a' | 'candidate_b' | 'tie';
  /** Debiased score for Candidate A in [0, 1] */
  debiasedScoreA: number;
  /** Debiased score for Candidate B in [0, 1] */
  debiasedScoreB: number;
  /** Detailed forward pass evaluation (A presented first, B second) */
  forwardPass: PairwisePassResult;
  /** Detailed reverse pass evaluation (B presented first, A second) */
  reversePass: PairwisePassResult;
  /** Whether position bias was detected (e.g. judge favored whichever candidate was placed first) */
  positionBiasDetected: boolean;
  /** Evaluator confidence score in [0, 1] based on cross-pass consistency */
  confidence: number;
  /** Consolidated reasoning summary */
  reasoning: string;
}

/**
 * Detailed trajectory reasoning and tool execution metrics.
 *
 * @see Liu et al., "AgentBench: Evaluating Large Language Models as Agents" (ICLR 2024)
 */
export interface TrajectoryEfficiencyMetrics {
  /** Ratio of minimal optimal steps to actual executed steps [0, 1] */
  stepEfficiency: number;
  /** Ratio of error-free tool calls to total tool calls [0, 1] */
  toolPrecision: number;
  /** Number of optimal steps expected */
  optimalSteps: number;
  /** Actual number of tool steps executed */
  actualSteps: number;
  /** Number of tool calls that resulted in errors or exceptions */
  failedToolCalls: number;
  /** Number of successfully executed tool calls */
  successfulToolCalls: number;
  /** Whether the trajectory completed within the optimal budget */
  isOptimal: boolean;
}

/**
 * Statistical summary of multi-trial evaluation runs for a single dataset item.
 */
export interface MultiTrialResult {
  /** Array of scores obtained across trials. */
  scores: number[];

  /** Mean mathematical score (mu) across trials. */
  meanScore: number;

  /** Standard deviation (sigma) of scores across trials. */
  standardDeviation: number;

  /** Percentage of trials that passed (0.0 to 1.0). */
  passRate: number;
}

/**
 * Consolidated evaluation result for a single dataset item across all metrics.
 */
export interface EvalItemResult {
  /** Benchmark dataset item. */
  item: EvalDatasetItem;

  /** Agent execution result. */
  agentResult: AgentResult;

  /** Individual metric evaluation results. */
  metrics: MetricResult[];

  /** Whether all metric evaluations passed. */
  overallPassed: boolean;

  /** Consolidated average score across metrics. */
  score: number;

  /** Optional multi-trial statistical variance summary. */
  multiTrialSummary?: MultiTrialResult;
}

/**
 * Overall benchmark summary output generated after running a dataset suite.
 */
export interface BenchmarkSummary {
  /** Total number of items evaluated. */
  totalItems: number;

  /** Number of items that passed all metrics. */
  passedItems: number;

  /** Number of items that failed one or more metrics. */
  failedItems: number;

  /** Overall pass rate (0.0 to 1.0). */
  passRate: number;

  /** Overall average score across all items (0.0 to 1.0). */
  averageScore: number;

  /** Statistical overall variance across all dataset items. */
  overallVariance: number;

  /** Detailed evaluation results per dataset item. */
  itemResults: EvalItemResult[];
}
