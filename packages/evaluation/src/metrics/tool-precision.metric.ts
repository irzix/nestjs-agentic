import type { AgentResult } from '@nestjs-agentic/core';
import type { EvalDatasetItem, EvalMetric, MetricResult } from '../interfaces/evaluation.interface';
import { getToolFailureReason, isToolExecutionFailed } from './tool-result';

/**
 * Options configuring ToolPrecisionMetric evaluation.
 */
export interface ToolPrecisionMetricOptions {
  /** Minimum precision threshold (0.0 to 1.0) required to pass. Default: `0.8` */
  minPrecisionThreshold?: number;
}

/**
 * Metric evaluator measuring the precision of tool calls in an agent trajectory.
 * Calculates the ratio of error-free, successful tool executions against total tool invocations.
 *
 * @see Liu et al., "AgentBench: Evaluating Large Language Models as Agents" (ICLR 2024)
 */
export class ToolPrecisionMetric implements EvalMetric {
  readonly name = 'ToolPrecision';
  private readonly minThreshold: number;

  constructor(options?: ToolPrecisionMetricOptions) {
    this.minThreshold = options?.minPrecisionThreshold ?? 0.8;
  }

  /**
   * Evaluates the tool invocation precision across the execution trajectory.
   *
   * @param item Benchmark dataset item.
   * @param result Output result generated by the agent runner.
   */
  evaluate(item: EvalDatasetItem, result: AgentResult): MetricResult {
    const toolCalls = result.toolCalls || [];
    const totalCalls = toolCalls.length;

    if (totalCalls === 0) {
      const expectedTools = item.expectedToolSequence?.length ?? 0;
      if (expectedTools === 0) {
        return {
          metricName: this.name,
          passed: true,
          score: 1.0,
          reason: 'No tool calls required and none executed',
          details: { totalCalls: 0, successfulCalls: 0, failedCalls: 0 },
        };
      } else {
        return {
          metricName: this.name,
          passed: false,
          score: 0.0,
          reason: `Expected ${expectedTools} tool calls, but agent executed 0`,
          details: { totalCalls: 0, expectedCalls: expectedTools },
        };
      }
    }

    let failedCalls = 0;
    const failedTools: Array<{ toolName: string; error?: string }> = [];

    for (const call of toolCalls) {
      if (isToolExecutionFailed(call)) {
        failedCalls++;
        failedTools.push({
          toolName: call.toolName,
          error: getToolFailureReason(call.result),
        });
      }
    }

    const successfulCalls = totalCalls - failedCalls;
    const precision = Number((successfulCalls / totalCalls).toFixed(4));
    const passed = precision >= this.minThreshold;

    return {
      metricName: this.name,
      passed,
      score: precision,
      reason: passed
        ? `Tool Precision (${precision}) meets threshold (${this.minThreshold}). ${successfulCalls}/${totalCalls} calls succeeded.`
        : `Tool Precision (${precision}) below threshold (${this.minThreshold}). ${failedCalls}/${totalCalls} calls failed.`,
      details: {
        totalCalls,
        successfulCalls,
        failedCalls,
        precision,
        failedTools,
      },
    };
  }
}
