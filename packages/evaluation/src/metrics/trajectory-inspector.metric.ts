import type { AgentResult } from '@nestjs-agentic/core';
import type {
  EvalDatasetItem,
  EvalMetric,
  MetricResult,
  TrajectoryEfficiencyMetrics,
} from '../interfaces/evaluation.interface';
import { isRecord, isToolExecutionFailed } from './tool-result';

/**
 * Configuration options for TrajectoryInspectorMetric.
 */
export interface TrajectoryInspectorOptions {
  /** Minimum trajectory sequence & argument score required to pass. Default: `1.0` */
  minScoreThreshold?: number;
  /** Whether to penalize trajectories that exceed optimal steps. Default: `true` */
  penalizeExtraSteps?: boolean;
}

/**
 * Metric evaluator that inspects the agent's tool call trajectory sequence,
 * verifies argument schema assertions, and computes step efficiency metrics.
 *
 * @see Liu et al., "AgentBench: Evaluating Large Language Models as Agents" (ICLR 2024)
 */
export class TrajectoryInspectorMetric implements EvalMetric {
  readonly name = 'TrajectoryInspector';
  private readonly minThreshold: number;
  private readonly penalizeExtraSteps: boolean;

  constructor(options?: TrajectoryInspectorOptions) {
    this.minThreshold = options?.minScoreThreshold ?? 1.0;
    this.penalizeExtraSteps = options?.penalizeExtraSteps ?? true;
  }

  /**
   * Evaluates the tool call trajectory sequence, argument values, and step efficiency.
   *
   * @param item Benchmark dataset item.
   * @param result Output result generated by the agent runner.
   */
  evaluate(item: EvalDatasetItem, result: AgentResult): MetricResult {
    const toolCalls = result.toolCalls || [];
    const actualSequence = toolCalls.map((t) => t.toolName);
    const actualSteps = toolCalls.length;

    // Calculate Step Efficiency:
    const optimalSteps = item.optimalSteps ?? item.expectedToolSequence?.length ?? Math.max(1, actualSteps);
    const stepEfficiency = Number(Math.min(1.0, optimalSteps / Math.max(actualSteps, 1)).toFixed(4));
    const isOptimal = actualSteps <= optimalSteps;

    // Count failed/successful tool calls
    let failedToolCalls = 0;
    for (const call of toolCalls) {
      if (isToolExecutionFailed(call)) {
        failedToolCalls++;
      }
    }
    const successfulToolCalls = actualSteps - failedToolCalls;
    const toolPrecision = actualSteps > 0 ? Number((successfulToolCalls / actualSteps).toFixed(4)) : 1.0;

    const efficiencyMetrics: TrajectoryEfficiencyMetrics = {
      stepEfficiency,
      toolPrecision,
      optimalSteps,
      actualSteps,
      failedToolCalls,
      successfulToolCalls,
      isOptimal,
    };

    // 1. Verify Expected Tool Sequence
    if (item.expectedToolSequence && item.expectedToolSequence.length > 0) {
      const expected = item.expectedToolSequence;
      let sequenceMatchCount = 0;

      for (let i = 0; i < expected.length; i++) {
        if (actualSequence[i] === expected[i]) {
          sequenceMatchCount++;
        }
      }

      const sequenceScore = sequenceMatchCount / expected.length;

      if (sequenceScore < 1.0) {
        return {
          metricName: this.name,
          passed: false,
          score: Number(sequenceScore.toFixed(4)),
          reason: `Tool sequence mismatch. Expected [${expected.join(' -> ')}], got [${actualSequence.join(' -> ')}]`,
          details: {
            actualSequence,
            expectedSequence: expected,
            ...efficiencyMetrics,
          },
        };
      }
    }

    // 2. Verify Tool Arguments
    if (item.expectedToolArgs) {
      for (const [toolName, expectedArgs] of Object.entries(item.expectedToolArgs)) {
        const matchingCalls = toolCalls.filter((t) => t.toolName === toolName);

        if (matchingCalls.length === 0) {
          return {
            metricName: this.name,
            passed: false,
            score: 0.0,
            reason: `Expected tool "${toolName}" was not called in trajectory`,
            details: { ...efficiencyMetrics },
          };
        }

        for (const call of matchingCalls) {
          for (const [argKey, expectedValue] of Object.entries(expectedArgs)) {
            const actualValue = isRecord(call.args) ? call.args[argKey] : undefined;
            if (actualValue !== expectedValue) {
              return {
                metricName: this.name,
                passed: false,
                score: 0.5,
                reason: `Tool "${toolName}" argument "${argKey}" mismatch. Expected "${expectedValue}", got "${actualValue}"`,
                details: {
                  toolName,
                  argKey,
                  expectedValue,
                  actualValue,
                  ...efficiencyMetrics,
                },
              };
            }
          }
        }
      }
    }

    // 3. Compute final score balancing sequence correctness and step efficiency
    let finalScore = 1.0;
    if (this.penalizeExtraSteps && !isOptimal) {
      finalScore = Number((0.7 + 0.3 * stepEfficiency).toFixed(4));
    }

    const passed = finalScore >= this.minThreshold;

    return {
      metricName: this.name,
      passed,
      score: finalScore,
      reason: passed
        ? `Agent trajectory verified (Step Efficiency: ${stepEfficiency}, Tool Precision: ${toolPrecision})`
        : `Agent trajectory score (${finalScore}) below threshold (${this.minThreshold})`,
      details: {
        actualSequence,
        ...efficiencyMetrics,
      },
    };
  }
}
